namespace Diddipoeler\Component\SportsManagement\Site\Helper;

\defined('_JEXEC') or die;

/**
 * Build external person-profile links used by site person views.
 */
final class PersonProfileRouteHelper
{
    /**
     * Build a Joomla Contacts profile route for the selected user.
     *
     * Uses the shared site route builder and retains the active
     * SportsManagement database selector for cross-component links.
     *
     * @param int $userId Joomla contact record identifier.
     * @param int $database Selected SportsManagement database number.
     * @return string Query route to the Joomla contact view.
     */
    public static function contact(int $userId, int $database = 0): string
    {
        return SiteRouteHelper::query([
            'option' => 'com_contact',
            'view' => 'contact',
            'id' => $userId,
            'cfg_which_database' => $database,
        ]);
    }

    /**
     * Build the legacy Community Builder Enhanced person-profile link.
     *
     * Preserves user, project, player and database parameters in the
     * canonical route generated by the native site route helper.
     *
     * @param int $userId Joomla user identifier.
     * @param int $projectId Selected SportsManagement project.
     * @param int $personId Selected SportsManagement person.
     * @param int $database Selected component database number.
     * @return string Query route to the external person profile.
     */
    public static function cbe(int $userId, int $projectId, int $personId, int $database = 0): string
    {
        return SiteRouteHelper::query([
            'option' => 'com_cbe',
            'view' => 'userProfile',
            'user' => $userId,
            'jlp' => $projectId,
            'jlpid' => $personId,
            'cfg_which_database' => $database,
        ]);
    }
}
